-- Create Stage for Document Storage
CREATE STAGE IF NOT EXISTS INSURANCE_DW.PRODUCTION.DOCUMENTS_STAGE;

-- Create Documents Table (stores metadata about generated PDFs)
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.RENEWAL_DOCUMENTS (
    DOCUMENT_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    POLICY_NUMBER VARCHAR(20) NOT NULL,
    DOCUMENT_TYPE VARCHAR(50) NOT NULL,
    FILE_NAME VARCHAR(255) NOT NULL,
    STAGE_PATH VARCHAR(500) NOT NULL,
    FILE_SIZE_BYTES INTEGER,
    STORAGE_LOCATION VARCHAR(50) DEFAULT 'SNOWFLAKE_STAGE',
    GENERATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP(),
    DOWNLOAD_URL VARCHAR(1000)
);

-- Create Email Notifications Table (stores email records with attachment paths)
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.EMAIL_NOTIFICATIONS (
    NOTIFICATION_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    POLICY_NUMBER VARCHAR(20) NOT NULL,
    RECIPIENT_EMAIL VARCHAR(100) NOT NULL,
    RECIPIENT_NAME VARCHAR(100),
    CC_EMAILS VARIANT,
    SUBJECT VARCHAR(255) NOT NULL,
    BODY TEXT,
    ATTACHMENT_PATH VARCHAR(500),
    ATTACHMENT_FILENAME VARCHAR(255),
    STATUS VARCHAR(20) DEFAULT 'PENDING',
    SENT_AT TIMESTAMP,
    ERROR_MESSAGE VARCHAR(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

-- Create indexes for better performance
CREATE INDEX IF NOT EXISTS idx_documents_policy ON INSURANCE_DW.PRODUCTION.RENEWAL_DOCUMENTS(POLICY_NUMBER);
CREATE INDEX IF NOT EXISTS idx_notifications_policy ON INSURANCE_DW.PRODUCTION.EMAIL_NOTIFICATIONS(POLICY_NUMBER);
CREATE INDEX IF NOT EXISTS idx_notifications_status ON INSURANCE_DW.PRODUCTION.EMAIL_NOTIFICATIONS(STATUS);

