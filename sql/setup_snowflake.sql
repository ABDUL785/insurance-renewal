-- ============================================================================
-- INSURANCE RENEWAL AGENT - SNOWFLAKE SCHEMA SETUP
-- ============================================================================
-- This script creates the required database, schema, and tables for the
-- Insurance Renewal Agent demo. Run this in your Snowflake environment.
-- ============================================================================

-- Create Database
CREATE DATABASE IF NOT EXISTS INSURANCE_DW;

-- Create Schema
CREATE SCHEMA IF NOT EXISTS INSURANCE_DW.PRODUCTION;

-- Create Policies Table
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.POLICIES (
    POLICY_NUMBER VARCHAR(20) NOT NULL,
    POLICY_HOLDER_ID VARCHAR(20) NOT NULL,
    POLICY_TYPE VARCHAR(50) NOT NULL,
    COVERAGE_EFFECTIVE_DATE DATE NOT NULL,
    COVERAGE_EXPIRATION_DATE DATE NOT NULL,
    ANNUAL_PREMIUM DECIMAL(12, 2) NOT NULL,
    POLICY_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    PAYMENT_STATUS VARCHAR(20) NOT NULL DEFAULT 'CURRENT',
    DEDUCTIBLE_AMOUNT DECIMAL(10, 2) DEFAULT 0,
    LAST_PAYMENT_DATE DATE,
    RENEWAL_ELIGIBILITY_FLAG VARCHAR(1) DEFAULT 'Y',
    AGENT_ID VARCHAR(20),
    PRIMARY KEY (POLICY_NUMBER)
);

-- Create Policy Holders Table
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.POLICY_HOLDERS (
    POLICY_HOLDER_ID VARCHAR(20) NOT NULL PRIMARY KEY,
    FIRST_NAME VARCHAR(50) NOT NULL,
    LAST_NAME VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(100),
    PHONE VARCHAR(20),
    ADDRESS_LINE_1 VARCHAR(100),
    ADDRESS_LINE_2 VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(2),
    ZIP_CODE VARCHAR(10),
    DATE_OF_BIRTH DATE,
    PREFERRED_CONTACT_METHOD VARCHAR(20) DEFAULT 'EMAIL'
);

-- Create Policy Coverages Table
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.POLICY_COVERAGES (
    ID AUTOINCREMENT,
    POLICY_NUMBER VARCHAR(20) NOT NULL,
    COVERAGE_TYPE VARCHAR(50) NOT NULL,
    COVERAGE_LIMIT DECIMAL(12, 2) NOT NULL,
    COVERAGE_PREMIUM DECIMAL(10, 2) NOT NULL,
    DEDUCTIBLE DECIMAL(10, 2) DEFAULT 0,
    CO_PAYMENT_PCT DECIMAL(5, 2) DEFAULT 0,
    IS_SUB_LIMIT VARCHAR(1) DEFAULT 'N',
    SUB_LIMIT_AMOUNT DECIMAL(12, 2),
    FOREIGN KEY (POLICY_NUMBER) REFERENCES POLICIES(POLICY_NUMBER)
);

-- Create Claims Table
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.CLAIMS (
    CLAIM_ID VARCHAR(20) NOT NULL PRIMARY KEY,
    POLICY_NUMBER VARCHAR(20) NOT NULL,
    CLAIM_DATE DATE NOT NULL,
    CLAIM_TYPE VARCHAR(50) NOT NULL,
    CLAIM_STATUS VARCHAR(20) NOT NULL,
    LOSS_DESCRIPTION VARCHAR(500),
    TOTAL_INCURRED_AMOUNT DECIMAL(12, 2) DEFAULT 0,
    PAID_AMOUNT DECIMAL(12, 2) DEFAULT 0,
    RESERVES_AMOUNT DECIMAL(12, 2) DEFAULT 0,
    CLAIM_YEAR INTEGER,
    FOREIGN KEY (POLICY_NUMBER) REFERENCES POLICIES(POLICY_NUMBER)
);

-- Create Experience Rating Table
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.EXPERIENCE_RATING (
    POLICY_NUMBER VARCHAR(20) NOT NULL PRIMARY KEY,
    POLICY_TYPE VARCHAR(50) NOT NULL,
    EFFECTIVE_YEARS INTEGER DEFAULT 0,
    TOTAL_CLAIMS INTEGER DEFAULT 0,
    TOTAL_INCURRED DECIMAL(12, 2) DEFAULT 0,
    CLAIMS_LAST_3_YEARS INTEGER DEFAULT 0,
    LOSS_RATIO DECIMAL(5, 4) DEFAULT 0,
    EXPERIENCE_MODIFIER DECIMAL(4, 3) DEFAULT 1.0,
    RISK_TIER VARCHAR(20) DEFAULT 'STANDARD',
    RECOMMENDED_PREMIUM_ADJUSTMENT DECIMAL(5, 2) DEFAULT 0,
    FOREIGN KEY (POLICY_NUMBER) REFERENCES POLICIES(POLICY_NUMBER)
);

-- Create Risk Tier Lookup Table
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.RISK_TIER_LOOKUP (
    POLICY_NUMBER VARCHAR(20) NOT NULL,
    RISK_TIER VARCHAR(20) NOT NULL,
    RISK_SCORE DECIMAL(5, 2),
    UNDERWRITING_CLASS VARCHAR(50),
    TERRITORY_CODE VARCHAR(10),
    PREMIUM_BAND VARCHAR(20),
    ELIGIBLE_FOR_DISCOUNT VARCHAR(1) DEFAULT 'N',
    DISCOUNT_REASON VARCHAR(100),
    FOREIGN KEY (POLICY_NUMBER) REFERENCES POLICIES(POLICY_NUMBER)
);

-- Create Market Rates Table
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.MARKET_RATES (
    POLICY_TYPE VARCHAR(50) NOT NULL,
    STATE VARCHAR(2) NOT NULL,
    BASE_RATE_PER_1000 DECIMAL(8, 4) NOT NULL,
    AVERAGE_PREMIUM DECIMAL(12, 2) NOT NULL,
    MARKET_TREND_PCT DECIMAL(5, 2) NOT NULL DEFAULT 8.0,
    RATE_CHANGE_YTD DECIMAL(5, 2) DEFAULT 0,
    COMPETITIVE_QUOTE_LOW DECIMAL(12, 2),
    COMPETITIVE_QUOTE_HIGH DECIMAL(12, 2),
    PRIMARY KEY (POLICY_TYPE, STATE)
);

-- Create Agents Table
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.AGENTS (
    AGENT_ID VARCHAR(20) NOT NULL PRIMARY KEY,
    AGENT_NAME VARCHAR(100) NOT NULL,
    AGENT_EMAIL VARCHAR(100),
    AGENT_PHONE VARCHAR(20),
    AGENT_TERRITORY VARCHAR(50),
    PRODUCER_CODE VARCHAR(20),
    APPOINTMENT_STATUS VARCHAR(20) DEFAULT 'ACTIVE'
);

-- Create H3 Risk Scores Table (reusing your existing data)
CREATE TABLE IF NOT EXISTS INSURANCE_DW.PRODUCTION.H3_RISK_SCORES (
    H3_INDEX VARCHAR(30) NOT NULL,
    H3_RESOLUTION INTEGER NOT NULL,
    H3_US_WILDFIRE_SCORE DECIMAL(5, 2),
    H3_US_PROPERTY_CRIME_SCORE DECIMAL(5, 2),
    H3_US_VIOLENT_CRIME_SCORE DECIMAL(5, 2),
    H3_US_SOCIETAL_CRIME_SCORE DECIMAL(5, 2),
    H3_US_MOTOR_VEHICLE_CRIME_SCORE DECIMAL(5, 2),
    H3_US_AUTO_FATALITY_SCORE DECIMAL(5, 2),
    H3_US_GL_SLIP_AND_FALL_SCORE DECIMAL(5, 2),
    H3_US_FIRE_SERVICE_SCORE DECIMAL(5, 2),
    H3_US_EARTHQUAKE_SCORE DECIMAL(5, 2),
    H3_US_FLOOD_SCORE DECIMAL(5, 2),
    H3_US_HAIL_SCORE DECIMAL(5, 2),
    H3_US_HURRICANE_SCORE DECIMAL(5, 2),
    H3_US_SHOCKFREEZE_SCORE DECIMAL(5, 2),
    H3_US_TORNADO_SCORE DECIMAL(5, 2),
    PRIMARY KEY (H3_INDEX)
);

